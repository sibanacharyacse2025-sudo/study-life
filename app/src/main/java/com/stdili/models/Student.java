package com.stdili.models;

public class Student {

    private String name;
    private int level;
    private int coins;
    private int activity;

    public String getName() {
        return name;
    }

    public int getLevel() {
        return level;
    }

    public int getCoins() {
        return coins;
    }

    public int getActivity() {
        return activity;
    }
}